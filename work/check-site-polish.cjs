const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = process.argv[2] || 'http://127.0.0.1:4174';
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  for (const width of [390, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 850 }, serviceWorkers: 'block' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(base);
    const music = page.frameLocator('#musicAppFrame');
    await music.locator('#grid .card').first().waitFor();
    assert.equal(await music.locator('.mini').isVisible(), false);
    const first = music.locator('#grid .card').first();
    await first.evaluate(el => el.dataset.qaStable = 'yes');
    await first.click();
    assert.equal(await first.getAttribute('data-qa-stable'), 'yes');
    assert.equal(await music.locator('.mini').isVisible(), true);
    assert.equal((await music.locator('.nav').boundingBox()).height, width === 390 ? 56 : 64);
    await music.locator('[data-nav="Profile"]').click();
    await page.waitForFunction(() => document.body.dataset.activeView === 'profile');
    assert.equal(await page.locator('[data-preset]').count(), 0);
    assert.equal(await page.locator('#themeControl button').count(), 2);
    await page.locator('[data-theme="light"]').click();
    assert.equal(await page.locator('body').evaluate(el => el.dataset.themePreset || ''), '');
    assert.equal(await page.locator('body').evaluate(el => getComputedStyle(el).color), 'rgb(59, 36, 95)');
    await page.locator('#bottomNav [data-app-view="screen"]').click();
    await page.locator('[data-section-filter="iu-official"]').click();
    const covers = await page.locator('.officialCategoryCard').evaluateAll(els => els.map(el => getComputedStyle(el).backgroundImage));
    assert.ok(covers.length > 0 && covers.every(src => src.includes('/assets/official-covers/')));
    await page.locator('.officialCategoryCard').first().click();
    await page.locator('.officialVideoCard__cover img').first().evaluate(img => img.decode());
    assert.ok(await page.locator('.officialVideoCard__cover img').first().evaluate(img => img.naturalWidth > 0));
    await page.screenshot({ path: `work/official-fixed-${width}.png` });
    await page.locator('#bottomNav [data-app-view="search"]').click();
    await page.locator('#globalSearchInput').fill('Dear my crazy soulmate');
    await page.waitForFunction(() => document.querySelector('#globalSearchResults').textContent.includes('Dear my crazy soulmate'));
    assert.ok(await page.locator('[data-detail-key^="local-track"]').count() > 0 || await page.locator('[data-detail-key]').count() > 0);
    const songId = await page.locator('#globalSearchResults [data-detail-key]').first().getAttribute('data-detail-key');
    assert.ok(await page.evaluate(id => window.IU_LOCAL_TRACKS.some(track => track.id === id), songId));
    await page.locator('#globalSearchResults [data-detail-key]').first().click();
    await page.waitForFunction(() => document.body.dataset.activeView === 'music');
    await music.locator('#title').filter({ hasText: 'Dear my crazy soulmate' }).waitFor();
    if (width === 390) assert.equal(await music.locator('#side').evaluate(el => el.classList.contains('open')), true);
    if (width === 390) await music.locator('#side .close').click();
    await music.locator('[data-nav="Search"]').click();
    await page.waitForFunction(() => document.body.dataset.activeView === 'search');
    await page.locator('#globalSearchType').selectOption('release');
    await page.locator('#globalSearchResults [data-search-release]').first().click();
    await page.waitForFunction(() => document.body.dataset.activeView === 'music');
    await music.locator('[data-tab="albums"].active').waitFor();
    assert.ok(await music.locator('#grid .card').count() > 0);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ width, officialCovers: 'local and loaded', themes: 2, search: 'current library linked', stableCards: true, miniPlayer: 'hidden until selection', errors }));
    await context.close();
  }
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
